// 界面上的中文要能显示，靠的是启动时把一款有中文字形的字体交给 FLTK。
//
// 字形从哪来，按顺序试两条：
//
// 1. 程序自带的字体（assets/fonts 下那份霞鹜文楷子集，构建时复制到可执行文件旁边）。
//    装在程序所在目录里找，找不到再找程序目录下的 fonts 子目录。这一条先试，是因为它
//    不依赖机器上装了什么中文字体，换一台没配过字体的机器也是同一副样子。
// 2. 系统自带的中文字体。找不到自带字体文件、或者注册不上时走这一条：Linux 问 fontconfig
//    要一款能显示简体中文的字体，Windows 试系统自带的几款。走这一条时界面照常打开，
//    只是字形与自带字体那份不同。
//
// 查到哪款就把哪款设成默认字体：四个正文字体位与四个等宽体位都指过去，
// FLTK 里所有没单独指定字体的控件都跟着用这一款。
#pragma once

#include <string>

namespace texttool::ui {

// 设置默认字体并返回实际选中的字体族名。
//
// program_path 是进程的 argv[0]，用它定位程序所在的目录；传空字符串时按当前工作目录找。
// 返回空字符串表示一款可用的中文字体都没找到，此时界面上的中文会显示成方框。
std::string install_cjk_font(const std::string& program_path);

}  // namespace texttool::ui
